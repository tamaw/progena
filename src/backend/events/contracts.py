def routine_run_status_event(status: str) -> str:
    """Return the canonical UI event name for one routine lifecycle status."""

    return _EVENT_VOCABULARY["templates"]["ROUTINE_RUN_STATUS"].format(status=status)


def _now_iso() -> str:
    return datetime.now(UTC).isoformat().replace("+00:00", "Z")


class UiEventEnvelope(BaseModel):
    id: str
    seq: int
    type: str
    scope: Literal["global", "session", "chat"] = "global"
    session_id: str | None = None
    payload: dict[str, Any] = Field(default_factory=dict)
    timestamp: str = Field(default_factory=_now_iso)
