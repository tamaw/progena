// Bundle the libraries agent-built modules may import into self-contained ESM
// files, and write the catalogue the agent reads at /modules/_catalogue.json.
//
// Modules run in a sandboxed, network-less iframe; their imports resolve through
// an import map to data: URLs built from these bundles (see
// src/lib/module-vendor/). Each bundle must therefore have no relative imports;
// cross-library imports (OrbitControls -> three) stay bare and resolve through
// the same map, so `three` is loaded exactly once.
//
// The bundles, libraries.js and the catalogue are committed. Run from
// app/frontend after changing a pinned version: `npm run build:module-vendor`.
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(frontendRoot, '../..');
const vendorDir = resolve(frontendRoot, 'src/lib/module-vendor');
const cataloguePath = resolve(repoRoot, 'data/modules/libraries.json');

const LIBRARIES = [
  {
    id: 'three',
    package: 'three',
    description: '3D rendering (WebGL): scenes, cameras, meshes, lights, materials.',
    entries: [
      { specifier: 'three', source: 'three', file: 'three.mjs' },
      {
        specifier: 'three/addons/controls/OrbitControls.js',
        // A file path, not a package subpath: esbuild's `external: ['three']`
        // would otherwise swallow this `three/...` entry itself.
        source: './node_modules/three/examples/jsm/controls/OrbitControls.js',
        file: 'three-orbit-controls.mjs',
        external: ['three'],
      },
    ],
    usage:
      "import * as THREE from 'three'; import { OrbitControls } from 'three/addons/controls/OrbitControls.js';",
  },
  {
    id: 'd3',
    package: 'd3',
    description: 'Data-driven SVG/canvas: scales, axes, shapes, force graphs, hierarchies, transitions.',
    entries: [{ specifier: 'd3', source: 'd3', file: 'd3.mjs' }],
    usage: "import * as d3 from 'd3';",
  },
];

async function packageVersion(name) {
  const pkg = JSON.parse(
    await readFile(resolve(frontendRoot, 'node_modules', name, 'package.json'), 'utf8'),
  );
  return pkg.version;
}

async function bundle(entry) {
  const result = await build({
    stdin: {
      contents: `export * from ${JSON.stringify(entry.source)};`,
      resolveDir: frontendRoot,
      loader: 'js',
    },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'inline',
    external: entry.external ?? [],
    write: false,
  });
  await writeFile(resolve(vendorDir, entry.file), result.outputFiles[0].contents);
}

await mkdir(vendorDir, { recursive: true });

const catalogue = { libraries: [] };
const loaderLines = [];
for (const library of LIBRARIES) {
  const version = await packageVersion(library.package);
  for (const entry of library.entries) {
    await bundle(entry);
    loaderLines.push(
      `  ${JSON.stringify(entry.specifier)}: () => import('./${entry.file}?raw').then((m) => m.default),`,
    );
  }
  catalogue.libraries.push({
    id: library.id,
    version,
    description: library.description,
    specifiers: library.entries.map((entry) => entry.specifier),
    usage: library.usage,
  });
}

await mkdir(dirname(cataloguePath), { recursive: true });
await writeFile(cataloguePath, `${JSON.stringify(catalogue, null, 2)}\n`);
await writeFile(
  resolve(vendorDir, 'libraries.js'),
  [
    '// Generated by scripts/build-module-vendor.mjs; do not edit.',
    '// Import specifier -> lazy loader of the bundled ESM source text.',
    'export const MODULE_LIBRARY_SOURCES = {',
    ...loaderLines,
    '};',
    '',
  ].join('\n'),
);

console.log(`Wrote ${loaderLines.length} bundles to ${vendorDir} and ${cataloguePath}`);
