"""Alerts routes."""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Callable, Coroutine
from typing import Any

from fastapi import APIRouter, Header, HTTPException, Request

import app.backend.alerts.service as alerts_service
import app.backend.events.documents as events_documents
import app.backend.events.stream as events_stream
import app.backend.http.contracts as http_contracts
import app.backend.http.requests as http_requests
from app.progenitor.document_kinds import (
    ALERT_KEY_PREFIX,
)

logger = logging.getLogger(__name__)

router = APIRouter()


def _alerts_payload() -> dict[str, object]:
    """Return the full alert payload for REST and SSE consumers."""
    return alerts_service.get_alerts_response().model_dump(mode="json")


@router.get("/alerts", status_code=202, response_model=http_contracts.UiRequestAcknowledgement)
async def get_alerts(
    request: Request,
    x_request_id: str | None = Header(default=None, alias="X-Request-ID"),
):
    """
    Get backend-managed alert history.

    Returns alerts generated by the progenitor agent.
    """
    request_id = http_requests.request_correlation_id(request, x_request_id)
    broadcast_alerts_state(request_id=request_id)
    return http_contracts.acknowledgement_response(request_id, ["alerts.updated"])


@router.post(
    "/alerts/viewed", status_code=202, response_model=http_contracts.UiRequestAcknowledgement
)
async def mark_viewed_alerts(
    request: Request,
    body: alerts_service.MarkAlertsViewedRequest | None = None,
    x_request_id: str | None = Header(default=None, alias="X-Request-ID"),
):
    """Mark alerts viewed without removing them from history."""
    request_id = http_requests.request_correlation_id(request, x_request_id)
    alerts_service.mark_alerts_viewed(body.alert_ids if body else None)
    broadcast_alerts_state(request_id=request_id)
    return http_contracts.acknowledgement_response(request_id, ["alerts.updated"])


@router.post(
    "/alerts/{alert_id}/dismiss",
    status_code=202,
    response_model=http_contracts.UiRequestAcknowledgement,
)
async def dismiss_alert(
    alert_id: str,
    request: Request,
    x_request_id: str | None = Header(default=None, alias="X-Request-ID"),
):
    """
    Dismiss an alert.

    Alerts remain in history; dismissing only clears unread state.
    """
    request_id = http_requests.request_correlation_id(request, x_request_id)
    alert = alerts_service.get_alert(alert_id)
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")

    alerts_service.mark_alerts_viewed([alert_id])
    broadcast_alerts_state(request_id=request_id)
    return http_contracts.acknowledgement_response(request_id, ["alerts.updated"])


@router.post(
    "/alerts/{alert_id}/respond",
    status_code=202,
    response_model=http_contracts.UiRequestAcknowledgement,
)
async def respond_to_alert(
    request: Request,
    alert_id: str,
    response: str = "acknowledged",
    x_request_id: str | None = Header(default=None, alias="X-Request-ID"),
):
    """
    Respond to an alert.

    Acknowledges the alert and optionally sends a response back to the agent.
    """
    request_id = http_requests.request_correlation_id(request, x_request_id)
    alert = alerts_service.get_alert(alert_id)
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")

    alerts_service.mark_alerts_viewed([alert_id])
    broadcast_alerts_state(request_id=request_id)
    logger.info("Alert %s responded with: %s", alert_id, response)

    return http_contracts.acknowledgement_response(request_id, ["alerts.updated"])


_alert_relay: Callable[[alerts_service.AlertInfo], Coroutine[Any, Any, None]] | None = None


_background_tasks: set[asyncio.Task[None]] = set()


def set_alert_relay(
    relay: Callable[[alerts_service.AlertInfo], Coroutine[Any, Any, None]] | None,
) -> None:
    global _alert_relay
    _alert_relay = relay


async def _publish_alert_document(typed: events_documents.TypedDocumentEvent) -> None:
    """Show alert changes in the alert center; relay new alerts to the user.

    Every producer writes an ``alert:<id>`` document, so this is the one
    delivery path.
    The relay is an LLM turn, so it runs in the background: a slow or failed
    relay never holds up document event dispatch.
    """

    event = typed.event
    if not event.key.startswith(ALERT_KEY_PREFIX):
        return
    broadcast_alerts_state()
    if event.op != "created" or not isinstance(event.after, dict):
        return
    alert = alerts_service.AlertInfo.model_validate(event.after)
    broadcast_alert(alert)
    if _alert_relay is not None:
        task = asyncio.create_task(_alert_relay(alert), name=f"alert-relay-{alert.id}")
        _background_tasks.add(task)
        task.add_done_callback(_background_tasks.discard)


def broadcast_alert(alert: alerts_service.AlertInfo):
    """Broadcast a new alert to all subscribers."""
    events_stream.broadcast_ui_event(
        "alert",
        {
            "id": alert.id,
            "type": alert.type,
            "title": alert.title,
            "message": alert.message,
            "urgent": alert.urgent,
        },
        scope="chat",
    )


def broadcast_alerts_state(*, request_id: str | None = None) -> None:
    """Broadcast full alert payload updates to subscribers."""
    events_stream.broadcast_ui_event("alerts.updated", _alerts_payload(), request_id=request_id)
